// Browser smoke test of the built static site, including repository subpath.
const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const base=process.env.PAGES_QA_URL||'http://127.0.0.1:5207/campus-ebike-charging-admin/'
async function main(){
 const browser=await chromium.launch({channel:'msedge',headless:true})
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[],apiRequests=[],failedAssets=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('request',r=>{if(new URL(r.url()).pathname.startsWith('/api/'))apiRequests.push(r.url())})
  page.on('response',r=>{if(r.status()>=400&&/\.(js|css)(\?|$)/.test(r.url()))failedAssets.push({url:r.url(),status:r.status()})})
  await page.goto(base+'#/dashboard')
  await page.locator('.metric-card').first().waitFor()
  assert.equal(await page.locator('.metric-card').count(),7)
  assert.equal(await page.locator('.login-submit').count(),0)
  await page.locator('.map-diagram').waitFor()
  assert.equal(await page.locator('.map-diagram .station-marker').count(),5)
  const screenshots=path.resolve(__dirname,'../docs/screenshots');fs.mkdirSync(screenshots,{recursive:true})
  await page.screenshot({path:path.join(screenshots,'pages-dashboard.png')})
  await page.locator('.navigation .nav-item').filter({hasText:'设备与插座'}).click()
  await page.getByLabel('筛选站点',{exact:true}).selectOption('ST04')
  await page.waitForFunction(()=>document.querySelector('.layout-summary strong')?.textContent==='西区校园示例站')
  assert.equal(await page.locator('.physical-row').count(),3)
  assert.deepEqual(await page.locator('.physical-row').evaluateAll(rows=>rows.map(row=>row.querySelectorAll('.physical-device').length)),[9,11,8])
  await page.locator('.management-glass').screenshot({path:path.join(screenshots,'station-layout.png')})
  await page.getByRole('button',{name:'管理员账号菜单',exact:true}).click()
  assert.equal(await page.getByRole('button',{name:'修改密码',exact:true}).count(),0)
  await page.getByRole('button',{name:'显示设置',exact:true}).click()
  await page.locator('.account-form label').filter({hasText:'全局字号'}).locator('select').selectOption('large')
  await page.locator('.account-form label').filter({hasText:'表格密度'}).locator('select').selectOption('compact')
  await page.locator('.account-form').getByRole('button',{name:'保存',exact:true}).click()
  await page.reload();await page.locator('.platform').waitFor()
  assert.equal(await page.locator('html').getAttribute('data-font-size'),'large')
  assert.equal(await page.locator('html').getAttribute('data-density'),'compact')
  await page.getByRole('button',{name:'通知中心',exact:true}).click()
  await page.getByRole('button',{name:'全部已读',exact:true}).click()
  await page.getByRole('button',{name:'全部已读',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'全部已读',exact:true}).isEnabled(),false)
  await page.getByRole('button',{name:'管理员账号菜单',exact:true}).click()
  await page.getByRole('button',{name:'退出演示',exact:true}).click()
  await page.getByRole('button',{name:'进入公开演示',exact:true}).click()
  await page.locator('.platform').waitFor()
  await page.locator('.navigation .nav-item').filter({hasText:'数据统计'}).click()
  await page.locator('.metric-card').first().waitFor()
  assert.deepEqual(apiRequests,[])
  assert.deepEqual(failedAssets,[])
  assert.deepEqual(errors,[])
  const proof={base,automaticDemoEntry:true,repoSubpathAssets:true,noBackendRequests:true,variedRows:true,preferencesSurviveReload:true,notificationsWork:true,demoReentry:true,pageErrors:errors}
  fs.writeFileSync(path.join(__dirname,'pages-verification.json'),JSON.stringify(proof,null,2)+'\n')
  console.log(JSON.stringify(proof,null,2))
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
