const {chromium}=require('playwright')
const assert=require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path')
const base=process.env.ADMIN_MAP_BASE||'http://127.0.0.1:5195'
async function main(){
 const browser=await chromium.launch({channel:'msedge',headless:true})
 try{
  const page=await browser.newPage({viewport:{width:1600,height:1100}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(base+'/#/dashboard')
  await page.locator('input[autocomplete=username]').fill(process.env.ADMIN_MAP_USER||'admin')
  await page.locator('input[autocomplete=current-password]').fill(process.env.ADMIN_MAP_PASSWORD||'Admin@123456')
  await page.locator('.login-submit').click();await page.locator('.station-map-card').waitFor()
  await page.locator('.map-loading').waitFor({state:'hidden',timeout:35000})
  assert.equal(await page.locator('.map-diagram').count(),0,'本次必须验证真实高德地图，不能以示意图算通过：'+await page.locator('.map-footnote').innerText())
  assert.equal(await page.evaluate(()=>{const script=[...document.scripts].find(s=>s.src.startsWith('https://webapi.amap.com/maps?'));return !!script&&new URL(script.src).searchParams.get('key')?.length===32}),true)
  await page.locator('.map-stage').scrollIntoViewIfNeeded()
  const a=page.getByRole('button',{name:'选择站点 中区教学区示例站',exact:true}),b=page.getByRole('button',{name:'选择站点 中区生活区示例站',exact:true})
  const separation=async()=>{const x=await a.boundingBox(),y=await b.boundingBox();return Math.hypot(x.x-y.x,x.y-y.y)}
  const before=await separation(),initialZoom=await page.getByLabel('当前地图缩放级别',{exact:true}).innerText(),stage=await page.locator('.map-stage').boundingBox()
  await page.mouse.move(stage.x+40,stage.y+50);await page.mouse.wheel(0,-400);await page.waitForTimeout(1000)
  const after=await separation()
  if(!(after>before*1.2))console.log(JSON.stringify({before,after,initialZoom,stage,zoom:await page.getByLabel('当前地图缩放级别',{exact:true}).innerText(),target:await page.evaluate(({x,y})=>{const el=document.elementFromPoint(x,y);return {tag:el?.tagName,classes:el?.className,scroll:scrollY}},{x:stage.x+40,y:stage.y+50})}))
  assert.ok(after>before*1.2,'滚轮向上应放大地图标记间距')
  const old=await a.boundingBox()
  await page.mouse.move(stage.x+60,stage.y+100);await page.mouse.down();await page.mouse.move(stage.x+180,stage.y+150,{steps:12});await page.mouse.up();await page.waitForTimeout(600)
  const moved=await a.boundingBox();assert.ok(Math.hypot(moved.x-old.x,moved.y-old.y)>50,'拖动地图应改变标记屏幕位置')
  console.log(JSON.stringify({configuredWebKey:true,realMap:true,wheelZoom:true,dragPan:true}))
  await page.getByLabel('地图搜索站点',{exact:true}).fill('生活区')
  await page.getByLabel('地图搜索站点',{exact:true}).press('Enter')
  await page.waitForFunction(()=>document.querySelector('.station-map-details h3')?.textContent==='中区生活区示例站',{},{timeout:3000})
  await page.getByRole('button',{name:'放大地图',exact:true}).waitFor()
  const zoom=()=>page.getByLabel('当前地图缩放级别',{exact:true}).innerText().then(Number)
  // Search starts a provider animation back to level 16. Wait for zoomend's
  // visible output before measuring the plus/minus round trip.
  await page.waitForFunction(()=>Number(document.querySelector('[aria-label="当前地图缩放级别"]').textContent)===16)
  const z=await zoom();await page.getByRole('button',{name:'放大地图',exact:true}).click()
  await page.waitForFunction(expected=>Number(document.querySelector('[aria-label="当前地图缩放级别"]').textContent)===expected,z+1)
  assert.ok(await zoom()>z)
  await page.getByRole('button',{name:'缩小地图',exact:true}).click()
  await page.waitForFunction(expected=>Number(document.querySelector('[aria-label="当前地图缩放级别"]').textContent)===expected,z)
  assert.ok(Math.abs(await zoom()-z)<0.1)
  await page.getByLabel('地图搜索站点',{exact:true}).fill('教学')
  await page.getByRole('button',{name:'搜索定位',exact:true}).click()
  await page.waitForFunction(()=>document.querySelector('.station-map-details h3')?.textContent==='中区教学区示例站')
  await page.getByLabel('地图搜索站点',{exact:true}).fill('示例站')
  await page.getByRole('button',{name:'搜索定位',exact:true}).click()
  await page.locator('.map-search-results button').filter({hasText:'中区体育馆示例站'}).click()
  await page.waitForFunction(()=>document.querySelector('.station-map-details h3')?.textContent==='中区体育馆示例站')
  await page.getByRole('button',{name:'定位当前站点',exact:true}).click()
  await page.waitForTimeout(1000)
  await page.locator('.station-map-card').screenshot({path:path.join(__dirname,'dashboard-map-interactions.jpg')})
  assert.deepEqual(errors,[])
  const proof={date:'2026-11-09',base,results:['实际加载Web端Key和高德底图','滚轮缩放与鼠标拖动实际改变地图','加减按钮改变可见缩放级别','搜索回车、定位按钮和多结果选择联动站点详情','可重新定位当前站点'],pageErrors:errors}
  fs.writeFileSync(path.join(__dirname,'map-interaction-verification.json'),JSON.stringify(proof,null,2)+'\n');console.log(JSON.stringify(proof,null,2))
 }finally{await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
