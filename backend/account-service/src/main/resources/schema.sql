CREATE TABLE IF NOT EXISTS eb_admin_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(64) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 display_name VARCHAR(60) NOT NULL,
 email VARCHAR(160) NOT NULL DEFAULT '',
 phone VARCHAR(24) NOT NULL DEFAULT '',
 bio VARCHAR(300) NOT NULL DEFAULT '',
 font_size VARCHAR(16) NOT NULL DEFAULT 'normal',
 density VARCHAR(16) NOT NULL DEFAULT 'comfortable',
 created_at VARCHAR(40) NOT NULL,
 updated_at VARCHAR(40) NOT NULL
);
-- Additive and idempotent for existing local account databases.
ALTER TABLE eb_admin_accounts ADD COLUMN IF NOT EXISTS avatar CLOB DEFAULT '' NOT NULL;
CREATE TABLE IF NOT EXISTS eb_admin_notice_reads (
 account_id BIGINT NOT NULL,
 event_key VARCHAR(220) NOT NULL,
 read_at VARCHAR(40) NOT NULL,
 PRIMARY KEY(account_id,event_key),
 FOREIGN KEY(account_id) REFERENCES eb_admin_accounts(id)
);
